package RdKw::WwW::SiteConf::Make;

use 5.006;
use strict;
use warnings;

=head1 NAME

RdKw::WwW::SiteConf::Make - Makefile backend for siteconf

=head1 SYNOPSIS

    my $text = RdKw::WwW::SiteConf::Make::emit($plan);

=head1 DESCRIPTION

I<$plan> is what C<< RdKw::WwW::SiteConf->plan >> returns, with a
C<prog> to credit in the header.  Each goal becomes a phony target,
the first of which is what a bare L<make(1)> builds; there is also a
C<clean>.  The one thing asked of L<make(1)> is that a recipe may be
a tab-indented shell fragment, so any make will do.

=cut

sub emit
{
	my ($plan) = @_;
	my $D = $plan->{D};
	my @goal = @{ $plan->{goals} };
	my (@all, %iHaz);
	for my $file (@{ $plan->{order} }) {
		push @all, $plan->{node}{$file}{bpath};
	}
	my @marker = map { $_->{marker} } @{ $plan->{dirs} };

	my $out = <<MAKE;
#
# Makefile!
# (generated by `$plan->{prog}' :D)
#
include MY/config.mk
.PHONY: @{[ join ' ', map { $_->{name} } @goal ]} clean
MAKE

	for my $goal (@goal) {
		my @target = map { $plan->{node}{$_}{bpath} } @{ $goal->{files} };
		$out .= "$goal->{name}: @target\n";
	}
	$out .= "clean:\n\trm -f @all @marker\n" if @all;
	$out .= "clean:\n" unless @all;

	for my $dir (@{ $plan->{dirs} }) {
		my $d = _quote($dir->{dir});
		$out .= "$dir->{marker}: @{ $dir->{deps} }\n";
		$out .= "\t[ -d $d ] || mkdir $d\n";
		$out .= "\t\@> $dir->{marker}\n";
	}

	for my $file (@{ $plan->{order} }) {
		my $node = $plan->{node}{$file};
		my $recipe = $node->{recipe};
		$recipe .= "\n" if length $recipe and $recipe !~ /\n\z/;
		$out .= "$node->{bpath}: @{ $node->{deps} }\n$recipe";
	}
	$out;
}

sub _quote
{
	my ($s) = @_;
	return $s if $s =~ m!\A[A-Za-z0-9_./:@%+=,-]+\z!;
	$s =~ s!'!'\\''!g;
	"'$s'";
}

1;
