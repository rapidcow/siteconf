package RdKw::WwW::SiteConf::Ninja;

use 5.008;
use strict;
use warnings;

use RdKw::WwW::SiteConf ();
our $VERSION = $RdKw::WwW::SiteConf::VERSION;

=head1 NAME

RdKw::WwW::SiteConf::Ninja - build.ninja backend for siteconf

=head1 SYNOPSIS

    my $text = RdKw::WwW::SiteConf::Ninja->_emit($plan);

=head1 DESCRIPTION

I<$plan> is what C<< RdKw::WwW::SiteConf->plan >> returns, with a
C<prog> to credit in the header.  Each goal is a C<phony> build
statement, the first of which is the C<default>.  Every file gets a
rule of its own (C<rule1>, C<rule2>, ...), holding the recipe from
F<Makefile.in>, since by now it has been spelled out for that very
file; the sources and the first dependency are the explicit inputs,
the rest are implicit, and the directory marker is order-only.

Recipes are written as for L<make(1)>, so this undoes make's reading
of them: each line is a command of its own (and so is run in a
subshell, as C<cd> would not carry over in make either), a backslash
joins lines, a leading C<@> is dropped and a leading C<-> ignores
failure.  For clean-up there is C<ninja -t clean>.

A space, C<:> or C<$> in a name is escaped (as C<$ >, C<$:> and
C<$$>); a vertical space (a line break, CR, form feed, ...) or a
C<|> cannot be, and is an error.

=cut

use RdKw::I18N::CodeSets ();
# (said as RdKw::WwW::SiteConf says it: see there)
use RdKw::L10N::TextDomain ':module' => 'RdKw::WwW::SiteConf::L10N';

sub _diag
{
	RdKw::I18N::CodeSets->locale->diag(@_);
}

sub _emit
{
	my ($class, $plan) = @_;
	my @goal = @{ $plan->{goals} };

	my $out = <<NINJA;
#
# build.ninja!
# (generated by `$plan->{prog}' :D)
#
ninja_required_version = 1.3

rule mkdir_marker
  command = [ -d \$dir ] || mkdir \$dir && > \$out
  description = MKDIR \$dir

NINJA

	for my $dir (@{ $plan->{dirs} }) {
		my $line = "build " . _path($dir->{marker}) . ": mkdir_marker";
		$line .= " || " . join ' ', map { _path($_) } @{ $dir->{deps} }
			if @{ $dir->{deps} };
		$out .= "$line\n  dir = " . _path($dir->{dir}) . "\n";
	}
	$out .= "\n" if @{ $plan->{dirs} };

	my $n = 0;
	for my $file (@{ $plan->{order} }) {
		my $node = $plan->{node}{$file};
		my $command = _command($node->{recipe});
		defined $command and length $command
			or die "E: " . _diag(__("%q: no recipe to make it (and ninja has no"
				. " way to make nothing)"), $file) . "\n";
		my $rule = 'rule' . ++$n;
		$out .= "rule $rule\n  command = $command\n";

		# Input first, then what we need but is not an input; what is
		# a marker only has to be there, not newer.
		my @dep = @{ $node->{deps} };
		my $input = $node->{nosrc} ? undef : shift @dep;
		my (@need, @order);
		for (@dep) {
			if (m{(?:\A|/)\Q$plan->{D}{e}\E\z}) { push @order, $_ }
			else { push @need, $_ }
		}
		my $build = "build " . _path($node->{bpath}) . ": $rule";
		$build .= " " . _path($input) if defined $input;
		$build .= " | " . join ' ', map { _path($_) } @need if @need;
		$build .= " || " . join ' ', map { _path($_) } @order if @order;
		$out .= "$build\n\n";
	}

	$out .= "build $_->{name}: phony "
		. join(' ', map { _path($plan->{node}{$_}{bpath}) } @{ $_->{files} })
		. "\n" for @goal;
	$out .= "\ndefault $goal[0]{name}\n" if @goal;
	$out;
}

# A path, as ninja wants to read it (which is never with a line
# break, nor with a `|', which ends it)
sub _path
{
	my ($s) = @_;
	$s =~ /([\n\cK\f\r\x{85}\x{2028}\x{2029}|])/
		# HEY!  the %s is a character, as `|' or U+000A
		and die "E: " . _diag(__("ninja cannot name %q (with %s in it)"),
			$s, $1 eq '|' ? "`|'" : sprintf('U+%04X', ord $1)) . "\n";
	$s =~ s/([ :\$])/\$$1/g;
	$s;
}

# make's recipe, in make's words, as one command in ninja's.  A lone
# `$' in it is for make, and we do not have any (`$$' stays `$$': it is
# `$' to the shell either way, and a `$' to ninja is written `$$').
sub _command
{
	my ($recipe) = @_;
	my @logical;
	my $joining;
	for my $line (split /\n/, $recipe) {
		if ($joining) {
			# make drops the tab of a continuation line
			$line =~ s/^\t//;
			$logical[-1] .= $line;
		} else {
			$line =~ s/^\t//;
			push @logical, $line;
		}
		# The backslash goes, and the newline with it, as the shell does.
		$joining = $logical[-1] =~ s/\\\z//;
	}

	my @cmd;
	for my $line (@logical) {
		next if $line =~ /\A[\t\n\cK\f\r ]*\z/;
		my $ignore = 0;
		# @ is for make to not echo, - is to not mind
		while ($line =~ s/\A[\t\n\cK\f\r ]*([-@+])[\t\n\cK\f\r ]*//) {
			$ignore = 1 if $1 eq '-';
		}
		$line =~ s/[\t\n\cK\f\r ]+\z//;
		# (grouped, so that `|| true' is not for what came before)
		$line = $ignore ? "( ( $line ) || true )" : "( $line )";
		push @cmd, $line;
	}
	join ' && ', @cmd;
}

1;
